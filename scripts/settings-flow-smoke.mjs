import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
const data=resolve('test-results/settings-flow-'+Date.now());mkdirSync(data,{recursive:true});
const app=await electron.launch({executablePath:process.env.OWL_TEST_EXECUTABLE,args:process.env.OWL_TEST_EXECUTABLE?[]:['.'],env:{...process.env,OWL_TEST_DATA_DIR:data}});
try {
 const page=await app.firstWindow();
 await page.getByRole('button',{name:'Make room for discovery'}).click();
 await page.getByRole('button',{name:'Create a set',exact:true}).first().click();
 assert.equal(await page.getByText('ADD YOUR CARDS',{exact:true}).count(),0,'Card entry must be separate from set creation');
 await page.getByLabel('Set name',{exact:true}).fill('Travel');
 await page.getByRole('button',{name:'Save set',exact:true}).click();
 await page.getByRole('button',{name:'Add cards',exact:true}).first().waitFor();
 let snapshot=await page.evaluate(()=>window.owl.snapshot());
 assert.equal(snapshot.decks.length,1);assert.equal(snapshot.words.length,0);
 await page.getByRole('button',{name:'Add cards',exact:true}).first().click();
 await page.getByText('ADD YOUR CARDS',{exact:true}).waitFor();
 assert.equal(await page.getByText('MAKE IT YOURS',{exact:true}).count(),0);
 await page.getByLabel('Word or phrase',{exact:true}).fill('journey');
 await page.getByLabel('Translation',{exact:true}).fill('путешествие');
 assert.equal(await page.getByRole('button',{name:'Add to preview'}).count(),0);
 await page.getByRole('button',{name:'Save cards',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('input[placeholder="Something worth remembering"]')?.value==='');
 assert.equal(await page.getByText('ADD YOUR CARDS',{exact:true}).count(),1,'Saving must leave card entry open');
 snapshot=await page.evaluate(()=>window.owl.snapshot());
 assert.equal(snapshot.decks.length,1);assert.equal(snapshot.words.length,1);assert.equal(snapshot.words[0].deckId,snapshot.decks[0].id);
 const deckId=snapshot.decks[0].id,wordId=snapshot.words[0].id;
 await page.getByRole('button',{name:'My sets',exact:true}).click();
 await page.getByRole('button',{name:'Options for Travel'}).click();
 await page.getByRole('button',{name:'Edit set',exact:true}).click();
 assert.equal(await page.getByText('ADD YOUR CARDS',{exact:true}).count(),0);
 await page.getByLabel('Set name',{exact:true}).fill('Travel words');
 await page.getByRole('button',{name:'Save set',exact:true}).click();
 await page.getByRole('button',{name:'Add cards',exact:true}).first().click();
 await page.getByRole('button',{name:'Paste text',exact:true}).click();
 await page.getByPlaceholder('hello — привет\nthank you — спасибо').fill('airport — аэропорт');
 await page.getByRole('button',{name:'Preview cards',exact:true}).click();
 await page.getByRole('button',{name:'Save selected cards',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('.draft-area'));
 assert.equal(await page.getByText('ADD YOUR CARDS',{exact:true}).count(),1);
 snapshot=await page.evaluate(()=>window.owl.snapshot());
 assert.equal(snapshot.decks[0].id,deckId);assert.equal(snapshot.decks[0].name,'Travel words');
 assert.equal(snapshot.words.length,2);assert.ok(snapshot.words.some(word=>word.id===wordId));
 assert.ok(snapshot.words.every(word=>word.deckId===deckId));
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 assert.equal(await page.getByRole('heading',{name:'Connection',exact:true}).count(),0);
 assert.equal(await page.getByLabel('API server').count(),0);
 await page.getByRole('button',{name:'Save preferences'}).click();
 await page.getByRole('button',{name:'Discover Premium'}).click();
 await page.getByRole('button',{name:'Continue with Google',exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Refresh subscription'}).count(),0);
 assert.equal(await page.getByRole('button',{name:'Manage Apple subscription'}).count(),0);
 await page.screenshot({path:'test-results/profile-updated.png',fullPage:true});
 console.log('PASS: separate set/card flows, hidden connection and subscription actions, Google account button.');
} finally {await app.close();}
